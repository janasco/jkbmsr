void test_parse_full_status_frame() {
  BatteryTelemetry t;
  TEST_ASSERT_TRUE(JkBmsParser::parseFrame(kStatusFrame, sizeof(kStatusFrame), t));
  TEST_ASSERT_TRUE(t.valid);
  TEST_ASSERT_EQUAL_UINT8(16, t.cellCount);
  TEST_ASSERT_FLOAT_WITHIN(0.001f, 3.271f, t.cellVoltages[0]);
  TEST_ASSERT_FLOAT_WITHIN(0.001f, 3.271f, t.cellVoltages[15]);
  TEST_ASSERT_FLOAT_WITHIN(0.001f, 3.268f, t.minCellVoltage);
  TEST_ASSERT_FLOAT_WITHIN(0.001f, 3.273f, t.maxCellVoltage);
  TEST_ASSERT_FLOAT_WITHIN(0.001f, 0.005f, t.deltaCellVoltage);
  TEST_ASSERT_FLOAT_WITHIN(0.01f, 52.32f, t.packVoltage);
  TEST_ASSERT_FLOAT_WITHIN(0.01f, 12.50f, t.packCurrent);
  TEST_ASSERT_FLOAT_WITHIN(0.5f, 654.0f, t.power);
  TEST_ASSERT_FLOAT_WITHIN(0.01f, 82.0f, t.stateOfCharge);
  TEST_ASSERT_FLOAT_WITHIN(0.01f, 45.0f, t.mosfetTemperature);
  TEST_ASSERT_FLOAT_WITHIN(0.01f, 26.0f, t.temperature1);
  TEST_ASSERT_FLOAT_WITHIN(0.01f, -25.0f, t.temperature2);
  TEST_ASSERT_EQUAL_UINT8(2, t.temperatureSensorCount);
  TEST_ASSERT_EQUAL_UINT32(42, t.cycleCount);
  TEST_ASSERT_FLOAT_WITHIN(0.5f, 12345.0f, t.cycleCapacityAh);
  TEST_ASSERT_FLOAT_WITHIN(0.5f, 280.0f, t.fullCapacityAh);
  TEST_ASSERT_FLOAT_WITHIN(0.5f, 229.6f, t.remainingCapacityAh);
  TEST_ASSERT_EQUAL_UINT32(0x0005, t.errorsBitmask);
  TEST_ASSERT_TRUE(t.chargingEnabled);
  TEST_ASSERT_TRUE(t.dischargingEnabled);
  TEST_ASSERT_TRUE(t.balancingActive);
  TEST_ASSERT_EQUAL_STRING("H7.X__S6.1.3S__", t.bmsSoftwareVersion.c_str());
  TEST_ASSERT_EQUAL_UINT8(1, t.protocolVersion);
  TEST_ASSERT_EQUAL_STRING("uart", t.source);
}

void test_discharge_current_sign() {
  uint8_t frame[sizeof(kStatusFrame)];
  memcpy(frame, kStatusFrame, sizeof(frame));
  // 0x84 value: clear bit 15 -> discharging. Fix up the additive checksum.
  const size_t currentHi = 11 + 2 + 48 + 1 + 12;
  const size_t declared = sizeof(frame) - 2;
  frame[currentHi] = static_cast<uint8_t>(frame[currentHi] & 0x7F);
  uint16_t crc = 0;
  for (size_t i = 0; i < declared; i++) crc += frame[i];
  frame[declared] = crc >> 8;
  frame[declared + 1] = crc & 0xFF;

  BatteryTelemetry t;
  TEST_ASSERT_TRUE(JkBmsParser::parseFrame(frame, sizeof(frame), t));
  TEST_ASSERT_FLOAT_WITHIN(0.01f, -12.50f, t.packCurrent);
}

void test_rejects_bad_checksum() {
  uint8_t frame[sizeof(kStatusFrame)];
  memcpy(frame, kStatusFrame, sizeof(frame));
  frame[sizeof(frame) - 1] ^= 0xFF;
  BatteryTelemetry t;
  TEST_ASSERT_FALSE(JkBmsParser::parseFrame(frame, sizeof(frame), t));
  TEST_ASSERT_FALSE(t.valid);
}

void test_rejects_truncated_frame() {
  BatteryTelemetry t;
  TEST_ASSERT_FALSE(JkBmsParser::parseFrame(kStatusFrame, sizeof(kStatusFrame) - 10, t));
}

void test_rejects_frames_without_header() {
  const uint8_t frame[] = {0x79, 0x01, 0x01, 0x0c, 0xc7, 0x83, 0x14, 0x78};
  BatteryTelemetry t;
  TEST_ASSERT_FALSE(JkBmsParser::parseFrame(frame, sizeof(frame), t));
}

void test_rejects_invalid_cell_index() {
  uint8_t frame[sizeof(kStatusFrame)];
  memcpy(frame, kStatusFrame, sizeof(frame));
  // First cell entry index 0 is out of range (cells are 1-based).
  frame[13] = 0x00;
  const size_t declared = sizeof(frame) - 2;
  uint16_t crc = 0;
  for (size_t i = 0; i < declared; i++) crc += frame[i];
  frame[declared] = crc >> 8;
  frame[declared + 1] = crc & 0xFF;
  BatteryTelemetry t;
  TEST_ASSERT_FALSE(JkBmsParser::parseFrame(frame, sizeof(frame), t));
}

void setup() {
  delay(2000);
  UNITY_BEGIN();
  RUN_TEST(test_parse_full_status_frame);
  RUN_TEST(test_discharge_current_sign);
  RUN_TEST(test_rejects_bad_checksum);
  RUN_TEST(test_rejects_truncated_frame);
  RUN_TEST(test_rejects_frames_without_header);
  RUN_TEST(test_rejects_invalid_cell_index);
  UNITY_END();
}

