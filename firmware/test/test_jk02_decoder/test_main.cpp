void test_decode_24s_real_capture() {
  BatteryTelemetry t;
  TEST_ASSERT_TRUE(decodeJk02CellInfo(kCellInfo24s, sizeof(kCellInfo24s), false, t));
  TEST_ASSERT_TRUE(t.valid);
  TEST_ASSERT_EQUAL_STRING("ble", t.source);
  TEST_ASSERT_EQUAL_UINT8(16, t.cellCount);
  TEST_ASSERT_FLOAT_WITHIN(0.001f, 3.327f, t.minCellVoltage);
  TEST_ASSERT_FLOAT_WITHIN(0.001f, 3.329f, t.maxCellVoltage);
  TEST_ASSERT_FLOAT_WITHIN(0.01f, 53.251f, t.packVoltage);
  TEST_ASSERT_FLOAT_WITHIN(0.001f, 0.0f, t.packCurrent);
  TEST_ASSERT_FLOAT_WITHIN(0.05f, 19.0f, t.temperature1);
  TEST_ASSERT_FLOAT_WITHIN(0.05f, 19.1f, t.temperature2);
  TEST_ASSERT_FLOAT_WITHIN(0.05f, 21.0f, t.mosfetTemperature);
  TEST_ASSERT_EQUAL_UINT32(0, t.errorsBitmask);
  TEST_ASSERT_FLOAT_WITHIN(0.01f, 84.0f, t.stateOfCharge);
  TEST_ASSERT_FLOAT_WITHIN(0.01f, 68.494f, t.remainingCapacityAh);
  TEST_ASSERT_FLOAT_WITHIN(0.01f, 81.0f, t.fullCapacityAh);
  TEST_ASSERT_EQUAL_UINT32(0, t.cycleCount);
  TEST_ASSERT_FLOAT_WITHIN(0.005f, 1.085f, t.cycleCapacityAh);
  TEST_ASSERT_EQUAL_UINT8(100, t.stateOfHealth);
  TEST_ASSERT_TRUE(t.chargingEnabled);
  TEST_ASSERT_TRUE(t.dischargingEnabled);
  TEST_ASSERT_FALSE(t.balancingActive);

  // Wire resistance array (offset 64, 0.001 Ohm/count per
  // syssi/esphome-jk-bms) — first cell, last active cell (16 of 16), and
  // one inactive slot past cellCount.
  TEST_ASSERT_FLOAT_WITHIN(0.0005f, 0.413f, t.wireResistanceOhms[0]);
  TEST_ASSERT_FLOAT_WITHIN(0.0005f, 0.389f, t.wireResistanceOhms[15]);
  TEST_ASSERT_FLOAT_WITHIN(0.0005f, 0.0f, t.wireResistanceOhms[16]);
}

void test_decode_32s_layout() {
  BatteryTelemetry t;
  TEST_ASSERT_TRUE(decodeJk02CellInfo(kCellInfo32s, sizeof(kCellInfo32s), true, t));
  TEST_ASSERT_EQUAL_UINT8(32, t.cellCount);
  TEST_ASSERT_FLOAT_WITHIN(0.001f, 3.300f, t.cellVoltages[0]);
  TEST_ASSERT_FLOAT_WITHIN(0.001f, 3.331f, t.cellVoltages[31]);
  TEST_ASSERT_FLOAT_WITHIN(0.01f, 105.632f, t.packVoltage);
  TEST_ASSERT_FLOAT_WITHIN(0.001f, -25.5f, t.packCurrent);
  TEST_ASSERT_FLOAT_WITHIN(0.05f, 45.2f, t.mosfetTemperature);
  TEST_ASSERT_FLOAT_WITHIN(0.05f, 30.5f, t.temperature1);
  TEST_ASSERT_FLOAT_WITHIN(0.05f, -10.5f, t.temperature2);
  TEST_ASSERT_EQUAL_UINT32(0x00010002, t.errorsBitmask);
  TEST_ASSERT_FLOAT_WITHIN(0.0005f, -1.2f, t.balancingCurrent);
  TEST_ASSERT_TRUE(t.balancingActive);
  TEST_ASSERT_FLOAT_WITHIN(0.01f, 66.0f, t.stateOfCharge);
  TEST_ASSERT_FLOAT_WITHIN(0.01f, 184.8f, t.remainingCapacityAh);
  TEST_ASSERT_FLOAT_WITHIN(0.01f, 280.0f, t.fullCapacityAh);
  TEST_ASSERT_EQUAL_UINT32(123, t.cycleCount);
  TEST_ASSERT_FLOAT_WITHIN(0.5f, 4567.0f, t.cycleCapacityAh);
  TEST_ASSERT_EQUAL_UINT8(99, t.stateOfHealth);
  TEST_ASSERT_TRUE(t.chargingEnabled);
  TEST_ASSERT_FALSE(t.dischargingEnabled);
}

void test_rejects_bad_crc() {
  uint8_t frame[sizeof(kCellInfo24s)];
  memcpy(frame, kCellInfo24s, sizeof(frame));
  frame[299] ^= 0xFF;
  BatteryTelemetry t;
  TEST_ASSERT_FALSE(decodeJk02CellInfo(frame, sizeof(frame), false, t));
}

void test_rejects_short_frame() {
  BatteryTelemetry t;
  TEST_ASSERT_FALSE(decodeJk02CellInfo(kCellInfo24s, 200, false, t));
}

void test_hardware_version_selects_layout() {
  // Device-info frame: header, type 0x03, hw version "14.XA" at offset 22.
  uint8_t frame[300] = {};
  frame[0] = 0x55; frame[1] = 0xAA; frame[2] = 0xEB; frame[3] = 0x90;
  frame[4] = 0x03;
  memcpy(frame + 6, "JK_B2A16S15P", 12);
  memcpy(frame + 22, "14.XA", 5);
  memcpy(frame + 30, "14.20", 5);
  uint8_t crc = 0;
  for (int i = 0; i < 299; i++) crc += frame[i];
  frame[299] = crc;

  Jk02DeviceInfo info;
  TEST_ASSERT_TRUE(decodeJk02DeviceInfo(frame, sizeof(frame), info));
  TEST_ASSERT_TRUE(info.is32s);
  TEST_ASSERT_EQUAL_STRING("14.XA", info.hardwareVersion.c_str());

  memcpy(frame + 22, "10.XW\0\0\0", 8);
  crc = 0;
  for (int i = 0; i < 299; i++) crc += frame[i];
  frame[299] = crc;
  TEST_ASSERT_TRUE(decodeJk02DeviceInfo(frame, sizeof(frame), info));
  TEST_ASSERT_FALSE(info.is32s);
}

void test_ble_command_surface_is_read_only() {
  TEST_ASSERT_TRUE(isJkBmsReadOnlyCommand(0x96));
  TEST_ASSERT_TRUE(isJkBmsReadOnlyCommand(0x97));
  TEST_ASSERT_FALSE(isJkBmsReadOnlyCommand(0x95));
  TEST_ASSERT_FALSE(isJkBmsReadOnlyCommand(0x98));
  TEST_ASSERT_FALSE(isJkBmsReadOnlyCommand(0xE1));
}

