#pragma once

#include <Arduino.h>
#include <NimBLEDevice.h>

#include "cloud/ProvisioningPayload.h"
#include "cloud/ProvisioningSession.h"

namespace jkbmsr {

/// What the app sent, once it committed a valid payload.
struct ProvisioningOutcome {
  bool applied = false;
  String ssid;
  String password;
  String timeZone;
  String claimToken;
};

/// The gateway's BLE setup service.
///
/// It is a thin radio shell around two things that are tested on the host: the
/// chunk buffer (a half-written payload must never look complete) and the
/// session (no credential write before the per-boot code). Everything this class
/// does that could be wrong without a compiler complaint is delegated to them.
///
/// The service is started only while the gateway cannot reach the network. A
/// running gateway must not be provisionable by anyone in range, and
/// provisioning must never share the radio with the pack link.
class BleProvisioningServer : private NimBLEServerCallbacks,
                             private NimBLECharacteristicCallbacks {
 public:
  static String advertisedName(const String& deviceId);

  /// Creates the service and starts advertising. [setupCode] is six digits.
  bool begin(const String& setupCode, const String& name);
  void end();

  /// Applies the session's timeouts. Call from the main loop.
  void tick(uint32_t nowMs);

  bool isActive() const { return active_; }
  bool hasOutcome() const { return outcomeReady_; }
  ProvisioningOutcome takeOutcome();

  ProvisioningState state() const { return session_.state(); }

 private:
  // The project builds against two NimBLE majors: 1.4.3 on arduino-esp32 2.x
  // targets and 2.5.1 on 3.x. Their callback signatures differ, and a mismatch
  // is a compile error on one target only, which is how a release matrix ships
  // half-broken.
#if defined(NIMBLE_CPP_VERSION_MAJOR) && NIMBLE_CPP_VERSION_MAJOR >= 2
  void onConnect(NimBLEServer* server, NimBLEConnInfo& connInfo) override;
  void onDisconnect(NimBLEServer* server, NimBLEConnInfo& connInfo, int reason) override;
  void onWrite(NimBLECharacteristic* characteristic, NimBLEConnInfo& connInfo) override;
#else
  void onConnect(NimBLEServer* server) override;
  void onDisconnect(NimBLEServer* server) override;
  void onWrite(NimBLECharacteristic* characteristic) override;
#endif

  void publishStatus(const String& text);
  void handleSetupCode(const uint8_t* data, size_t length, uint32_t nowMs);
  void handlePayload(const uint8_t* data, size_t length);
  void handleCommit(uint32_t nowMs);

  NimBLEServer* server_ = nullptr;
  NimBLEService* service_ = nullptr;
  NimBLECharacteristic* statusChar_ = nullptr;
  NimBLECharacteristic* setupChar_ = nullptr;
  NimBLECharacteristic* payloadChar_ = nullptr;
  NimBLECharacteristic* commandChar_ = nullptr;

  ProvisioningSession session_{String("000000")};
  ProvisioningBuffer buffer_;
  ProvisioningOutcome outcome_;
  bool active_ = false;
  bool outcomeReady_ = false;
};

/// Six digits, stable while the gateway is unprovisioned.
///
/// Stable because the normal flow moves the gateway from USB power to the pack,
/// which reboots it: a code regenerated per boot would be dead before the owner
/// reached the app. Regenerated by a factory reset, which also clears the
/// identity it protects.
String loadOrCreateSetupCode();
void resetSetupCode();

}  // namespace jkbmsr
